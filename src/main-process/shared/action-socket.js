'use strict';

// Fast path for GNOME custom keybindings on Linux.
//
// Launching a second Electron process per keypress (single-instance forwarding)
// takes ~0.8 s, so users pressed again and toggles cancelled out. Instead the
// running app listens on a private Unix socket (mode 0600, in userData) and the
// GNOME keybinding runs a tiny shell script that writes the action id to it.
// If the app isn't running (no socket), the script falls back to launching the
// app with --action=<id>, which still works through single-instance forwarding.

const fs = require('fs');
const net = require('net');
const path = require('path');

const SOCKET_FILE = 'action.sock';
const SCRIPT_FILE = 'gnome-shortcut.sh';
const ACTION_ID_RE = /^[A-Za-z][A-Za-z0-9]{0,63}$/;

function getActionSocketPath(userDataPath) {
  return path.join(userDataPath, SOCKET_FILE);
}

function getGnomeShortcutScriptPath(userDataPath) {
  return path.join(userDataPath, SCRIPT_FILE);
}

function shSingleQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

// fallbackArgv: the argv (without --action) that starts the app, e.g.
// [execPath, appPath, '--no-sandbox'] from source or [appImagePath] packaged.
function buildGnomeShortcutScript({ socketPath, fallbackArgv }) {
  if (!socketPath) throw new Error('socketPath is required');
  if (!Array.isArray(fallbackArgv) || fallbackArgv.length === 0) throw new Error('fallbackArgv is required');
  const launch = fallbackArgv.map(shSingleQuote).join(' ');
  return [
    '#!/bin/sh',
    '# Generated by Open Cluely for GNOME custom keybindings. Safe to delete;',
    '# "Remove from GNOME shortcuts" in Settings deletes it.',
    `SOCK=${shSingleQuote(socketPath)}`,
    'ACTION="$1"',
    'case "$ACTION" in ""|*[!A-Za-z0-9]*) exit 2 ;; esac',
    'if [ -S "$SOCK" ] && command -v python3 >/dev/null 2>&1; then',
    `  python3 -c 'import socket,sys
s=socket.socket(socket.AF_UNIX); s.settimeout(1); s.connect(sys.argv[1]); s.sendall(sys.argv[2].encode()); s.close()' "$SOCK" "$ACTION" 2>/dev/null && exit 0`,
    'fi',
    `exec ${launch} --action="$ACTION"`,
    ''
  ].join('\n');
}

function isSocketAlive(socketPath) {
  return new Promise((resolve) => {
    const client = net.connect(socketPath);
    client.once('connect', () => { client.destroy(); resolve(true); });
    client.once('error', () => resolve(false));
  });
}

// isKnownAction(id) must reject anything that isn't a configured shortcut id.
async function startActionSocketServer({ socketPath, isKnownAction, onAction, log = console }) {
  if (await isSocketAlive(socketPath)) {
    // Another live instance owns it (single-instance should prevent this).
    log.warn('[ActionSocket] Socket already in use; fast shortcut path disabled.');
    return { close() {} };
  }
  try { fs.unlinkSync(socketPath); } catch (_) { /* no stale socket */ }

  const server = net.createServer((conn) => {
    let buf = '';
    conn.setEncoding('utf8');
    conn.setTimeout(1000, () => conn.destroy());
    conn.on('data', (chunk) => {
      buf += chunk;
      if (buf.length > 64) conn.destroy();
    });
    conn.on('end', () => {
      const id = buf.trim();
      if (ACTION_ID_RE.test(id) && isKnownAction(id)) {
        try { onAction(id); } catch (error) { log.error('[ActionSocket] Action failed:', error && error.message); }
      } else {
        log.warn('[ActionSocket] Ignoring unknown action');
      }
    });
    conn.on('error', () => {});
  });
  server.on('error', (error) => log.error('[ActionSocket] Server error:', error && error.message));

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    // umask so the socket is never briefly world-accessible
    const previousUmask = process.umask(0o177);
    try {
      server.listen(socketPath, () => { server.off('error', reject); resolve(); });
    } finally {
      process.umask(previousUmask);
    }
  });
  try { fs.chmodSync(socketPath, 0o600); } catch (_) { /* best effort */ }

  return {
    close() {
      try { server.close(); } catch (_) { /* ignore */ }
      try { fs.unlinkSync(socketPath); } catch (_) { /* ignore */ }
    }
  };
}

module.exports = {
  ACTION_ID_RE,
  buildGnomeShortcutScript,
  getActionSocketPath,
  getGnomeShortcutScriptPath,
  shSingleQuote,
  startActionSocketServer
};
